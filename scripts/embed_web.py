# PlatformIO pre-build script: embed the web files the device serves into
# src/web_assets.h as C++ raw string literals (generated; gitignored).
#   web/device.html -> DEVICE_HTML   the portal page
#   web/common.css  -> COMMON_CSS    shared with the online dashboard
#   web/common.js   -> COMMON_JS     shared with the online dashboard
# The header is only rewritten when a file changed, so unchanged builds don't
# recompile the portal.
import os

Import("env")  # noqa: F821 (provided by PlatformIO)

ROOT = env["PROJECT_DIR"]  # noqa: F821
FILES = [("DEVICE_HTML", "web/device.html"), ("COMMON_CSS", "web/common.css"), ("COMMON_JS", "web/common.js")]
DELIM = "WEBASSET"

out = ["#pragma once", "#include <Arduino.h>", "// Generated by scripts/embed_web.py from web/. Do not edit."]
for name, rel in FILES:
    text = open(os.path.join(ROOT, rel), encoding="utf-8").read()
    if ")" + DELIM + '"' in text:
        raise SystemExit("%s contains the raw-string delimiter %s" % (rel, DELIM))
    out.append('static const char %s[] PROGMEM = R"%s(%s)%s";' % (name, DELIM, text, DELIM))
data = "\n".join(out) + "\n"

path = os.path.join(env["PROJECT_SRC_DIR"], "web_assets.h")  # noqa: F821
old = open(path, encoding="utf-8").read() if os.path.exists(path) else None
if data != old:
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(data)
